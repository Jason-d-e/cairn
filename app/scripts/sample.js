// Writes web/src/cover/sample.ts and web/src/cover/passage.ts from one real answer, so the cover never shows a
// hand-typed result. The passage file keeps only the opening of the quoted passage (the cover shows forty words).
// Usage: node scripts/sample.js   (the server must be running with a model key)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const BASE = process.env.CAIRN_URL ?? 'http://127.0.0.1:3100'
const CAMPUS = process.env.CAIRN_CAMPUS ?? 'my'
const QUESTIONS = { en: 'I was sick on the day of my exam. Can I defer it?', zh: '考试当天生病没去考，可以申请延期考试吗？' }

async function ask(question) {
  const res = await fetch(`${BASE}/api/ask`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-cairn-source': 'eval' }, body: JSON.stringify({ question, campus: CAMPUS }) })
  const body = await res.json()
  if (!res.ok) throw new Error(`${res.status}: ${body.error?.message}`)
  return body
}

const en = await ask(QUESTIONS.en)
const zh = await ask(QUESTIONS.zh)
for (const [lang, r] of [['en', en], ['zh', zh]]) console.log(lang, r.status, `${r.checks.quotes_verified}/${r.checks.quotes_total} verified`, '-', r.answer)
if (en.status !== 'answered' || zh.status !== 'answered') {
  console.error('Both answers must be "answered" before they go on the cover. Nothing written.')
  process.exit(1)
}
// The English quote shown is the first verified citation of the English answer; the sentence shown per language is that language's own answer.
const quote = [...en.citations, ...en.points].find((q) => q.verified)
const day = new Date().toLocaleDateString('sv-SE') // the local day, YYYY-MM-DD
const sample = `// The answer shown on the cover. Regenerated from a real run by scripts/sample.js, never typed by hand.
// Run on ${day} with ${en.meta.model_served}, campus ${CAMPUS}, corpus ${en.meta.corpus}.
export const SAMPLE = {
  date: ${JSON.stringify(day)},
  campus: ${JSON.stringify(CAMPUS)},
  question: ${JSON.stringify(QUESTIONS)},
  answer: ${JSON.stringify({ en: en.answer, zh: zh.answer })},
  quote: ${JSON.stringify(quote.quote)},
  source_id: ${JSON.stringify(quote.source_id)},
  doc: ${JSON.stringify(quote.doc)},
  title: ${JSON.stringify(quote.title)},
  section: ${JSON.stringify(quote.section)},
  page_campus: ${JSON.stringify(quote.campus ?? null)},
  url: ${JSON.stringify(quote.url)},
  verified: ${quote.verified},
}
`
fs.writeFileSync(path.join(APP, 'web', 'src', 'cover', 'sample.ts'), sample)
console.log('wrote web/src/cover/sample.ts')

// The passage the sample quotes: its opening sixty words (the cover shows forty) and its length, with the link.
const text = quote.source_text ?? ''
const passage = `// The passage the cover's sample quotes, from data/chunks.json: its opening only, with a link to the page.
// Page text © its publisher (see the footer notice); regenerated by scripts/sample.js.
export const PASSAGE = {
  id: ${JSON.stringify(quote.source_id)},
  title: ${JSON.stringify(quote.title)},
  section: ${JSON.stringify(quote.section)},
  campus: ${JSON.stringify(quote.campus ?? null)},
  url: ${JSON.stringify(quote.url)},
  chars: ${text.length},
  text: ${JSON.stringify(text.split(/\s+/).slice(0, 60).join(' '))},
}
`
fs.writeFileSync(path.join(APP, 'web', 'src', 'cover', 'passage.ts'), passage)
console.log('wrote web/src/cover/passage.ts')
