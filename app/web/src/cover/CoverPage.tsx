function shot(lang: string, name: string) {
  return `${import.meta.env.BASE_URL}shots/${lang === 'zh' ? 'zh' : 'en'}/${name}.webp`
}

/** Scrolls to a section on the cover without touching the hash router. */
function jump(id: string) {
  return (e: MouseEvent) => {
    e.preventDefault()
    document.getElementById(id)?.scrollIntoView({ behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth', block: 'start' })
  }
}

/** The bar retracts while reading down and returns on the way up (passive, frame-throttled listener). */
function useRetractingBar() {
  const [hidden, setHidden] = useState(false)
  useEffect(() => {
    let last = window.scrollY
    let ticking = false
    const onScroll = () => {
      if (ticking) return
      ticking = true
      requestAnimationFrame(() => {
        const y = window.scrollY
        setHidden(y > 160 && y > last)
        last = y
        ticking = false
      })
    }
    window.addEventListener('scroll', onScroll, { passive: true })
    return () => window.removeEventListener('scroll', onScroll)
  }, [])
  return hidden
}

/** Which "moment" panel is in the middle of the screen, so the pinned screen can follow it. */
function useActivePanel(count: number) {
  const refs = useRef<(HTMLElement | null)[]>([])
  const [active, setActive] = useState(0)
  useEffect(() => {
    const io = new IntersectionObserver(
      (entries) => entries.forEach((e) => e.isIntersecting && setActive(Number((e.target as HTMLElement).dataset.index))),
      { rootMargin: '-45% 0px -45% 0px' },
    )
    refs.current.slice(0, count).forEach((el) => el && io.observe(el))
    return () => io.disconnect()
  }, [count])
  return { refs, active }
}

/** '#/?s=what' from another page: scroll to that section once, then drop the query. */
function useSectionFromHash() {
  useEffect(() => {
    const m = window.location.hash.match(/[?&]s=([a-z]+)/)
    if (!m) return
    window.history.replaceState(null, '', '#/')
    requestAnimationFrame(() => document.getElementById(m[1])?.scrollIntoView({ block: 'start' }))
  }, [])
}

/** The signature: one real answer, exactly as the desk shows it. Regenerated by scripts/sample.js, never typed. */
function SampleCard({ lang, labelled = true }: { lang: Lang; labelled?: boolean }) {
  const { t } = useTranslation()
  const answer = SAMPLE.answer[lang]
  const quotes = [SAMPLE.quote]
  const sources = [{ id: SAMPLE.doc, title: SAMPLE.title, campus: SAMPLE.page_campus }]
  return (
    <div className="hm-sample clear clear--lead">
      {labelled && <p className="hm-sample-label">{t('cover.hero.sampleLabel', { date: SAMPLE.date, campus: t(`campus.names.${SAMPLE.campus}`) })}</p>}
      <p className="hm-sample-q">{SAMPLE.question[lang]}</p>
      <p className="hm-sample-a">
        <KeySentence text={answer} quotes={quotes} criteria={[SAMPLE.doc]} />
      </p>
      <Facts text={answer} quotes={quotes} criteria={sources} />
      <blockquote lang="en" className="hm-sample-quote" cite={SAMPLE.url}>
        <p><mark>{SAMPLE.quote}</mark></p>
      </blockquote>
      <p className="hm-sample-src">
        <span className="cn-tag" data-ok="true">{t('desk.quote.verified')}</span>
        <a className="cn-link" href={SAMPLE.url} rel="noreferrer">
          {t('desk.quote.read')} <IconExternalLink size={12} aria-hidden style={{ verticalAlign: '-1px' }} />
        </a>
      </p>
    </div>
  )
}

